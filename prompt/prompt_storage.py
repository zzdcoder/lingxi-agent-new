# -----------------------------------------------------------------------------
# §25 P2-4：工具能力边界条款
#
# 生产 trace=0e7fc2dd93554f24：用户问「统计用户 dada 有多少条消息会话」，
# 现有工具做不到（当时还没有聚合工具，且 conversation_message 没有 user_id
# 关联列）。模型的实际行为**不是**调用 ask_user，而是把「请提供筛选条件」
# 这类问题写进了**回答正文**，同时继续换参数重试 —— 24 次 LLM 调用后
# 用户拿到的是一段看起来像报告、实则没解决问题的文字。
#
# 根因是提示词只说了「缺信息就追问」，从未说「工具做不到时也该追问」，
# 更没说「禁止同参重试」。补上这段，让「能力边界」成为模型的一等公民概念。
# -----------------------------------------------------------------------------
_TASK_CAPABILITY_CLAUSE = """

关于工具的能力边界（重要，务必先判断）：
- 现在能做的：列出授权表清单、按**等值条件**查询明细、聚合统计
  （count/sum/avg/min/max，可按某列分组）、检索知识库、单表写操作。
- **现在做不到的**（不要试图用参数组合绕过去）：跨表关联查询（JOIN）、
  子查询、任意 SQL、模糊匹配/LIKE、时间范围比较（大于/小于某个日期）、
  按任意字段排序取 TopN（聚合分组除外）、一次导出全部数据。
- 凡遇到「有多少条 / 总共有多少 / 数量 / 求和 / 平均 / 最多 / 最少」这类问题，
  **必须调用 aggregate_data**，不要用 query_data 拉明细后自己数——
  query_data 最多返回 50 行，数出来的结果必然是错的。
- 判定为「工具做不到」后的正确动作（**按顺序**）：
  1. **不要**用相同或几乎相同的参数再次调用同一个工具（重试不会改变结果）；
  2. 先看能否换一种**现有工具可表达**的等价问法（例如改为统计整张表的行数）；
  3. 仍不行则**调用 ask_user**，明确说明能力边界 + 给出 2~3 个可替代的问法让用户选。
- **严禁**把追问或「无法完成」的说明埋在回答正文里就算完事：
  那会让用户以为任务已经完成。要么调用 ask_user（走正式追问卡片），
  要么明确以「未完成」的措辞收尾。"""


TASK_AGENT_SYSTEM_PROMPT = (
    _TASK_AGENT_SYSTEM_PROMPT_BASE
    + (
        _TASK_CAPABILITY_CLAUSE
        if getattr(settings, "agent_task_prompt_capability_clause", True)
        else ""
    )
)


